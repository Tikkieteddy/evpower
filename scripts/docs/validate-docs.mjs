// Validates handover documentation against the repository.
// Usage: npm run docs:validate   (exit code 1 on any failure)
// Checks: broken relative links, referenced source files, storage keys present in source,
// dashboard freshness/offline-ness, and secret leakage into docs.
/* global process, console */
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const failures = [];
const warnings = [];
const fail = (msg) => failures.push(msg);
const read = (p) => readFileSync(resolve(root, p), "utf8");
const repoRel = (abs) => relative(root, abs).replaceAll("\\", "/");

const walk = (dir, exts) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full, exts);
    return exts.some((e) => name.endsWith(e)) ? [full] : [];
  });

const docFiles = [
  ...["CLAUDE.md", "HANDOVER.md", "DOCUMENT_INDEX.md", "START_HERE_CLAUDE.md", "README.md"].map((f) => resolve(root, f)),
  ...walk(resolve(root, "docs/handover"), [".md", ".html", ".mmd", ".json"]),
];

// 1. Relative links in Markdown and HTML.
const linkPattern = /\]\(([^)\s]+)\)|href="([^"]+)"/g;
let linkCount = 0;
for (const file of docFiles.filter((f) => /\.(md|html)$/.test(f))) {
  for (const match of read(file).matchAll(linkPattern)) {
    const target = (match[1] || match[2]).split("#")[0];
    if (!target || /^(https?:|mailto:)/.test(target)) continue;
    linkCount += 1;
    if (!existsSync(resolve(dirname(file), decodeURI(target)))) fail(`Broken link in ${repoRel(file)} → ${target}`);
  }
}

// 2. Files referenced by the single data source exist; storage keys exist in source.
const data = JSON.parse(read("docs/handover/data/project-status.json"));
for (const item of [...data.features, ...data.screens, ...data.storage, ...data.documents]) {
  const p = item.file && item.file.includes("/") ? item.file : item.path;
  if (p && !p.includes("*") && !existsSync(resolve(root, p))) fail(`project-status.json references missing file: ${p}`);
}
const srcText = walk(resolve(root, "src"), [".js", ".jsx"]).map((f) => readFileSync(f, "utf8")).join("\n");
for (const s of data.storage) if (!srcText.includes(`"${s.key}"`)) fail(`Storage key not found in src: ${s.key}`);

// 3. Dashboard: generated, current, offline.
const dashboardPath = "docs/handover/HANDOVER_DASHBOARD.html";
const dashboard = read(dashboardPath);
if (!dashboard.includes("GENERATED by scripts/docs/build-dashboard.mjs")) fail("Dashboard is not generated — run npm run docs:build");
if (statSync(resolve(root, "docs/handover/data/project-status.json")).mtimeMs > statSync(resolve(root, dashboardPath)).mtimeMs)
  fail("project-status.json is newer than the dashboard — run npm run docs:build");
if (/<(script|link|img)[^>]+(src|href)="https?:/i.test(dashboard)) fail("Dashboard loads an external resource (must work offline)");
if (!dashboard.includes(data.meta.dashboardFooter)) fail("Dashboard footer standard missing");

// 4. Secrets must not leak into documentation (README is excluded: it is owner-maintained source, reported separately).
const secretPatterns = [/ghp_[A-Za-z0-9]{20,}/, /github_pat_/, /BEGIN [A-Z ]*PRIVATE KEY/, /AIza[0-9A-Za-z_-]{30}/, /sk-[A-Za-z0-9]{20,}/];
const defaultPassword = (srcText.match(/loginPassword = "([^"]+)"/) || [])[1];
for (const file of docFiles.filter((f) => !f.endsWith("README.md"))) {
  const text = read(file);
  if (secretPatterns.some((re) => re.test(text))) fail(`Secret-like token in ${repoRel(file)}`);
  if (defaultPassword && text.includes(defaultPassword)) fail(`Default credential value appears in ${repoRel(file)}`);
}
if (defaultPassword && read("README.md").includes(defaultPassword)) warnings.push("README.md still prints the default admin credential (owner decision pending)");

for (const w of warnings) console.warn(`WARN  ${w}`);
for (const f of failures) console.error(`FAIL  ${f}`);
console.log(`${failures.length ? "FAILED" : "OK"}: ${docFiles.length} doc files, ${linkCount} relative links, ${data.features.length} features, ${data.storage.length} storage keys checked`);
process.exit(failures.length ? 1 : 0);
